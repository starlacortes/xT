import Foundation

/// Emits `xT/Shared/ZoneID.swift` from the seed table.
///
/// The 49 zone labels were previously stringly-typed in five separate places — the centroid
/// JSON, the generator's `ZONES` table, `preferredZones`, `recommendedZones`, and the shader
/// upload — with nothing checking they agreed. Generating the enum from the same table the
/// bake uses means the compiler catches drift.
///
/// `rawValue` is deliberately the persisted string: `InjectionSite.zoneLabel` is the migration
/// key for existing dose history, so these values are a storage contract and cannot be
/// prettified.
enum ZoneIDGenerator {

    static func write(seeds: [ZoneSeed], to url: URL) throws {
        var out = """
        // Generated by tools/zonebake — do not edit by hand.
        //
        // Run `swift run zonebake` to regenerate after changing ZoneSeeds.swift.
        //
        // `rawValue` is the string persisted in `InjectionSite.zoneLabel` and is the migration
        // key for a user's dose history and avoid-zone settings. Changing any raw value orphans
        // existing records.

        /// The 49 clinical zones, in the same order as the baked zone map's zone IDs.
        enum ZoneID: String, CaseIterable, Identifiable, Sendable {

        """

        for seed in seeds {
            out += "    case \(caseName(for: seed.label)) = \"\(seed.label)\"\n"
        }

        out += """

            var id: String { rawValue }

            /// The zone's display name. Identical to `rawValue` today, but kept separate so a
            /// label can be reworded in the UI without breaking stored records.
            var displayName: String { rawValue }
        }

        """
        try out.write(to: url, atomically: true, encoding: .utf8)
    }

    /// "Upper Left Abdomen" → "upperLeftAbdomen"
    private static func caseName(for label: String) -> String {
        let words = label.split(separator: " ").map(String.init)
        guard let first = words.first else { return "unknown" }
        return ([first.lowercased()] + words.dropFirst().map { $0.capitalized }).joined()
    }
}
